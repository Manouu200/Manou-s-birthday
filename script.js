/* ---------- Langue ---------- */
let currentLang = 'en';
let selectedChoice = '';
let messageState = null; // null | { type: 'pick' } | { type: 'done', name }
const APPS_SCRIPT_URL = "https://formspree.io/f/mwlvwodj";

function renderMessage() {
  const box = document.getElementById('rsvp-message');
  const dict = translations[currentLang];
  if (!messageState) { box.textContent = ''; return; }
  box.textContent = messageState.type === 'pick'
    ? dict.pickFirst
    : dict.thanks(messageState.name, messageState.choice || (selectedChoice ? (dict['choice.' + selectedChoice] || selectedChoice) : ''));
}

function applyLang(lang) {
  if (!translations[lang]) lang = 'en';
  currentLang = lang;
  const dict = translations[lang];

  document.documentElement.lang = lang;
  document.title = dict.title;

  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = dict[el.dataset.i18n]; });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = dict[el.dataset.i18nHtml]; });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = dict[el.dataset.i18nPlaceholder]; });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', dict[el.dataset.i18nAria]); });
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.setAttribute('aria-pressed', String(btn.dataset.lang === lang));
  });

  renderMessage();
  try { localStorage.setItem('lang', lang); } catch (e) { /* stockage indisponible */ }
}

document.querySelectorAll('.lang-btn').forEach((btn) => {
  btn.addEventListener('click', () => applyLang(btn.dataset.lang));
});

function detectLang() {
  try {
    const saved = localStorage.getItem('lang');
    if (saved && translations[saved]) return saved;
  } catch (e) { /* ignore */ }
  return (navigator.language || '').toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

/* ---------- Menu des boissons (modale) ---------- */
const menuModal = document.getElementById('menu-modal');
document.getElementById('open-menu').addEventListener('click', () => {
  menuModal.classList.add('open');
  // Reset carousel to first image when opening
  const images = document.querySelectorAll('.carousel-image');
  const indicators = document.querySelectorAll('.carousel-indicator');
  if (window._carouselState && images.length > 0) {
    window._carouselState.currentIndex = 0;
    images.forEach((img, idx) => img.classList.toggle('active', idx === 0));
    indicators.forEach((ind, idx) => ind.classList.toggle('active', idx === 0));
  }
});
document.getElementById('close-menu').addEventListener('click', () => menuModal.classList.remove('open'));
menuModal.addEventListener('click', (event) => {
  if (event.target === menuModal) menuModal.classList.remove('open');
});
document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape') menuModal.classList.remove('open');
});

/* ---------- RSVP ---------- */
document.querySelectorAll('.rsvp-btn').forEach((button) => {
  button.addEventListener('click', () => {
    document.querySelectorAll('.rsvp-btn').forEach((item) => item.classList.remove('active'));
    button.classList.add('active');
    selectedChoice = button.dataset.choice;
  });
});

document.getElementById('rsvp-form').addEventListener('submit', async (event) => {
  event.preventDefault();
  const name = document.getElementById('guest-name').value.trim();
  if (!selectedChoice) {
    messageState = { type: 'pick' };
    renderMessage();
    return;
  }
  const btn = document.querySelector('.rsvp-submit');
  const oldText = btn.textContent;
  btn.disabled = true;
  btn.textContent = currentLang === 'fr' ? 'Envoi...' : 'Sending...';
  try {
    const dict = translations[currentLang];
    const choiceLabel = dict['choice.' + selectedChoice] || selectedChoice;
    const res = await fetch(APPS_SCRIPT_URL, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Accept': 'application/json'
      },
      body: JSON.stringify({ name, choice: choiceLabel, email: 'manou@example.com' })
    });
    const data = await res.json().catch(() => ({}));
    if (data && data.ok === false) throw new Error(data.error || 'Server returned error');
    if (res.status >= 400) throw new Error('Request failed');
    messageState = { type: 'done', name, choice: choiceLabel };
    document.getElementById('rsvp-form').reset();
    document.querySelectorAll('.rsvp-btn').forEach((b) => b.classList.remove('active'));
    selectedChoice = '';
  } catch (e) {
    alert(currentLang === 'fr' ? "Oups, l'envoi a échoué. Réessaie." : "Oops, sending failed. Try again.");
  } finally {
    btn.disabled = false;
    btn.textContent = oldText;
    renderMessage();
  }
});

/* ---------- Menu carousel ---------- */
document.addEventListener('DOMContentLoaded', () => {
  const prevBtn = document.getElementById('carousel-prev');
  const nextBtn = document.getElementById('carousel-next');
  const images = document.querySelectorAll('.carousel-image');
  const indicatorsContainer = document.getElementById('carousel-indicators');
  
  if (prevBtn && nextBtn && images.length > 0) {
    const state = { currentIndex: 0 };
    window._carouselState = state;
    
    // Create indicators
    indicatorsContainer.innerHTML = '';
    images.forEach((_, index) => {
      const indicator = document.createElement('button');
      indicator.className = 'carousel-indicator';
      indicator.setAttribute('aria-label', `Go to slide ${index + 1}`);
      indicator.addEventListener('click', () => goToSlide(index));
      indicatorsContainer?.appendChild(indicator);
    });
    
    const indicators = document.querySelectorAll('.carousel-indicator');
    
    function updateCarousel() {
      images.forEach((img, index) => {
        img.classList.toggle('active', index === state.currentIndex);
      });
      indicators.forEach((ind, index) => {
        ind.classList.toggle('active', index === state.currentIndex);
      });
    }
    
    function goToSlide(index) {
      state.currentIndex = index;
      updateCarousel();
    }
    
    prevBtn.addEventListener('click', () => {
      state.currentIndex = (state.currentIndex - 1 + images.length) % images.length;
      updateCarousel();
    });
    
    nextBtn.addEventListener('click', () => {
      state.currentIndex = (state.currentIndex + 1) % images.length;
      updateCarousel();
    });
    
    // Keyboard navigation
    document.addEventListener('keydown', (e) => {
      if (!menuModal.classList.contains('open')) return;
      if (e.key === 'ArrowLeft') {
        const s = window._carouselState || state;
        s.currentIndex = (s.currentIndex - 1 + images.length) % images.length;
        updateCarousel();
      }
      if (e.key === 'ArrowRight') {
        const s = window._carouselState || state;
        s.currentIndex = (s.currentIndex + 1) % images.length;
        updateCarousel();
      }
    });
    
    updateCarousel();
  }
});
document.addEventListener('click', (event) => {
  if (event.target.closest('button, a')) {
    const sparkle = document.createElement('span');
    sparkle.className = 'sparkle';
    sparkle.textContent = ['✦', '♡', '✧', '✿'][Math.floor(Math.random() * 4)];
    sparkle.style.left = `${event.clientX}px`;
    sparkle.style.top = `${event.clientY}px`;
    sparkle.style.color = Math.random() > .5 ? '#ff3e9d' : '#d83228';
    document.body.appendChild(sparkle);
    setTimeout(() => sparkle.remove(), 850);
  }
});

